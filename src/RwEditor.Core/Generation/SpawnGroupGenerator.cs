using System.Globalization;
using System.Text;
using RwEditor.Core.Mod;
using RwEditor.Core.Settings;
using RwEditor.Core.Validation;

namespace RwEditor.Core.Generation;

/// <summary>The two generated include files, as text (UTF-8 without BOM when written, LF line ends, trailing LF).</summary>
public sealed record GeneratedFiles(string AnchorGroups, string SelectorGroups)
{
    public IReadOnlyDictionary<string, string> ByRelPath => new Dictionary<string, string>(StringComparer.Ordinal)
    {
        [EditorSupport.AnchorGenerated] = AnchorGroups,
        [EditorSupport.SelectorGenerated] = SelectorGroups,
    };

    public static readonly UTF8Encoding Encoding = new(false);
}

/// <summary>Settings that failed validation. Nothing was generated or written.</summary>
public sealed class SettingsInvalidException : EditorRefusalException
{
    public SettingsInvalidException(IReadOnlyList<Finding> findings)
        : base("SETTINGS_INVALID", "the settings are not valid for this mod:\n  " + string.Join("\n  ", findings.Where(f => f.Severity == Severity.Error)))
    { Findings = findings; }

    public IReadOnlyList<Finding> Findings { get; }
}

/// <summary>
/// The spawn-group generator (DESIGN_EDITOR 2.4): a pure function from (settings, mod) to the text of editorGenerated/anchorGroups.ini and
/// editorGenerated/selectorGroups.ini. It reads the mod only through <see cref="ModContext"/> (unit display names, building flag, radius) and
/// never touches the disk. The output for the design's 2-group sample is byte-identical to DESIGN_EDITOR 2.4 (golden tests), and every output
/// satisfies the include rules of tools/check-start-spawner.ps1 (ii-m)/(iv-m) and tools/check-option-sections.ps1 (f).
/// </summary>
public static class SpawnGroupGenerator
{
    /// <summary>Version of the generated-text format (printed in the header). Changing any emitted byte means a new format version and new golden files.</summary>
    public const string FormatVersion = "0.1.0";

    public const string AnchorHeader = "# GENERATED by Depache RW Editor " + FormatVersion + " (schema 1). Do not edit by hand.";
    public const string SelectorHeader = "# GENERATED by Depache RW Editor " + FormatVersion + " (schema 1). Do not edit by hand: the editor rewrites this file.";

    public const string Confirmed = "numberOfUnitsInNeutralTeam(withTag='gameOptionsConfirmed') > 0";
    /// <summary>The C-025 human-only term, identical to the four default spawns.</summary>
    public const string HumanOnlyTerm = "not (numberOfUnitsInNeutralTeam(withTag='extraHuman') > 0 and self.isControlledByAI)";
    public const string NotAi = "not self.isControlledByAI";
    public const int SelectorGroupPos = 8002;
    public const string Section4TypeId = "4";

    /// <summary>Validates, then generates. Throws <see cref="SettingsInvalidException"/> when any validation error exists.</summary>
    public static GeneratedFiles Generate(EditorSettings settings, ModContext mod)
    {
        var findings = SettingsValidator.Validate(settings, mod);
        if (findings.Any(f => f.Severity == Severity.Error)) throw new SettingsInvalidException(findings);
        return GenerateUnchecked(settings, mod);
    }

    /// <summary>Generation without validation. Only for callers that validated already (and for negative tests).</summary>
    internal static GeneratedFiles GenerateUnchecked(EditorSettings settings, ModContext mod)
    {
        var groups = ActiveGroups(settings);
        return new GeneratedFiles(Anchor(settings, groups, mod), Selector(settings, groups, mod));
    }

    /// <summary>The output for the default settings (no groups, nothing hidden): the shipped behaviour. Needs no validation.</summary>
    public static GeneratedFiles GenerateDefaults(ModContext mod) => GenerateUnchecked(EditorSettings.Default(), mod);

    /// <summary>The groups that are generated: enabled ones, by slot.</summary>
    public static IReadOnlyList<SpawnGroup> ActiveGroups(EditorSettings s) => s.SpawnGroups.Where(g => g.Enabled).OrderBy(g => g.Slot).ToList();

    public static string Tag(int slot) => "ug" + slot.ToString("00", CultureInfo.InvariantCulture);

    // ------------------------------------------------------------------ anchor
    static string Anchor(EditorSettings settings, IReadOnlyList<SpawnGroup> groups, ModContext mod)
    {
        var sb = new StringBuilder();
        Line(sb, "[core]");
        Line(sb, "dont_load: true");
        Line(sb, AnchorHeader);
        if (groups.Count == 0) return sb.ToString();

        Line(sb, "");
        Line(sb, "[hiddenAction_ugInit]");
        Line(sb, "id:ugInit");
        Line(sb, "autoTriggerOnEvent: created");
        Line(sb, "temporarilyAddTags: " + string.Join(", ", new[] { "xGrpWait" }.Concat(groups.Select(g => "ugW" + Nn(g.Slot)))));

        foreach (var g in groups)
        {
            string nn = Nn(g.Slot), tag = Tag(g.Slot), done = tag + "Done";
            Line(sb, "");
            Line(sb, $"[hiddenAction_{tag}S]");
            Line(sb, $"id:{tag}S");
            Line(sb, "autoTrigger: " + SpawnTrigger(g.Slot, g.Mode));
            Line(sb, "addGlobalTeamTags: " + done);
            Line(sb, "spawnUnits: " + SpawnList(g, settings, mod));
            Line(sb, $"[hiddenAction_{tag}R]");
            Line(sb, $"id:{tag}R");
            Line(sb, "autoTrigger: " + ReleaseTrigger(g.Slot, g.Mode));
            Line(sb, "temporarilyRemoveTags: ugW" + nn);
        }

        Line(sb, "");
        Line(sb, "[hiddenAction_ugGate]");
        Line(sb, "id:ugGate");
        Line(sb, "autoTrigger: " + GateTrigger(groups.Select(g => g.Slot)));
        Line(sb, "temporarilyRemoveTags: xGrpWait");
        return sb.ToString();
    }

    public static string SpawnTrigger(int slot, GroupMode mode)
    {
        string tag = Tag(slot);
        string baseTrig = $"if self.timeAlive > 1 and {Confirmed} and numberOfUnitsInNeutralTeam(withTag='{tag}') > 0 and not self.globalTeamTags(includes=\"{tag}Done\")";
        return baseTrig + " and " + (mode == GroupMode.HumansOnly ? NotAi : HumanOnlyTerm);
    }

    public static string ReleaseTrigger(int slot, GroupMode mode)
    {
        string tag = Tag(slot), nn = Nn(slot);
        string rel = $"if {Confirmed} and self.tags(includes=\"ugW{nn}\") and (self.globalTeamTags(includes=\"{tag}Done\") or numberOfUnitsInNeutralTeam(withTag='{tag}') < 1";
        return rel + (mode == GroupMode.HumansOnly ? " or self.isControlledByAI)" : ")");
    }

    public static string GateTrigger(IEnumerable<int> slots) =>
        "if self.tags(includes=\"xGrpWait\")" + string.Concat(slots.OrderBy(s => s).Select(s => $" and not self.tags(includes=\"ugW{Nn(s)}\")"));

    static string SpawnList(SpawnGroup g, EditorSettings settings, ModContext mod)
    {
        var offsets = PlannedOffsets(g, settings, mod, out var reason) ?? throw new InvalidOperationException("layout failed after validation: " + reason);
        var parts = new List<string>();
        int k = 0;
        foreach (var u in g.Units)
        {
            bool building = mod.FindUnit(u.Unit)?.IsBuilding == true;
            // DESIGN_EDITOR 2.3: mobile units never skip and never snap; buildings snap to the grid and skip when the spot is taken, so they never stack.
            string flags = building ? "skipIfOverlapping=true, gridAlign=true" : "skipIfOverlapping=false, gridAlign=false";
            for (int c = 0; c < u.Count; c++, k++)
                parts.Add($"{u.Unit}({flags}, offsetX={offsets[k].X.ToString(CultureInfo.InvariantCulture)}, offsetY={offsets[k].Y.ToString(CultureInfo.InvariantCulture)})");
        }
        return string.Join(", ", parts);
    }

    /// <summary>
    /// The offset of every copy, in spawn order: the explicit offsets when the settings give them (all units of the group must then have them), else
    /// <see cref="Layout.Auto"/>. Null with a reason when no placement is possible.
    /// </summary>
    public static IReadOnlyList<Offset>? PlannedOffsets(SpawnGroup g, EditorSettings s, ModContext mod, out string? reason)
    {
        reason = null;
        if (g.Units.All(u => u.Offsets != null))
            return g.Units.SelectMany(u => u.Offsets!).ToList();
        var copies = new List<(string, double?)>();
        foreach (var u in g.Units)
            for (int c = 0; c < Math.Max(0, u.Count); c++) copies.Add((u.Unit, mod.FindUnit(u.Unit)?.Radius));
        // the sector is shared by the generated groups; a disabled group is placed as if it were enabled (so it can be switched on as it is)
        var slots = ActiveGroups(s).Select(x => x.Slot).Append(g.Slot).Distinct().OrderBy(x => x).ToList();
        return Layout.Auto(slots.IndexOf(g.Slot), slots.Count, copies, out reason);
    }

    // ------------------------------------------------------------------ selector
    static string Selector(EditorSettings s, IReadOnlyList<SpawnGroup> groups, ModContext mod)
    {
        var sb = new StringBuilder();
        Line(sb, "[core]");
        Line(sb, "dont_load: true");
        Line(sb, SelectorHeader);

        var hidden = HiddenTags(s, mod);
        var defaults = groups.Where(g => g.DefaultOn).Select(g => Tag(g.Slot)).ToList();
        if (hidden.Count > 0 || defaults.Count > 0) Line(sb, "");
        if (hidden.Count > 0)
        {
            Line(sb, "[hiddenAction_ugHide]");
            Line(sb, "id:ugHide");
            Line(sb, "autoTriggerOnEvent: created");
            Line(sb, "temporarilyAddTags: " + string.Join(", ", hidden.Select(t => "xh" + t)));
        }
        if (defaults.Count > 0)
        {
            Line(sb, "[hiddenAction_ugDef]");
            Line(sb, "id:ugDef");
            Line(sb, "autoTriggerOnEvent: created");
            Line(sb, "temporarilyAddTags: " + string.Join(", ", defaults));
        }

        foreach (var g in groups)
        {
            string tag = Tag(g.Slot);
            Line(sb, "");
            Line(sb, $"[action_{tag}On]");
            Line(sb, "@copyFromSection: template_turnOnOption");
            Line(sb, "@define actionTag: " + tag);
            Line(sb, "@define actionName: " + g.Name);
            Line(sb, "@define actionNameZh: " + g.Name);
            Line(sb, "@define typeId: " + Section4TypeId);
            Line(sb, "pos: " + SelectorGroupPos.ToString(CultureInfo.InvariantCulture));
            Line(sb, "description:" + Description(g, mod));
            Line(sb, $"[action_{tag}Off]");
            Line(sb, $"@copyFromSection: action_{tag}On, template_turnOffOption");
            Line(sb, $"[action_{tag}Msg]");
            Line(sb, $"@copyFromSection: action_{tag}On, template_notificationAction");
        }
        return sb.ToString();
    }

    /// <summary>Option tags hidden (Hidden or Deleted), in the selector's own file order.</summary>
    public static IReadOnlyList<string> HiddenTags(EditorSettings s, ModContext mod) =>
        mod.Options.Where(o => s.GetOptionState(o.Tag) != OptionState.Shown).Select(o => o.Tag).ToList();

    /// <summary>The On button's description: who gets the group, then one "- Nx Display name" line per unit entry (a literal \n separates lines).</summary>
    public static string Description(SpawnGroup g, ModContext mod)
    {
        var lines = new List<string>
        {
            g.Mode == GroupMode.HumansOnly ? "- Human players start with this group (AI never)" : "- Every player starts with this group",
        };
        foreach (var u in g.Units)
            lines.Add($"- {u.Count.ToString(CultureInfo.InvariantCulture)}x {NameRules.DisplayForDescription(mod.FindUnit(u.Unit)?.DisplayText, u.Unit)}");
        return string.Join("\\n", lines);
    }

    static string Nn(int slot) => slot.ToString("00", CultureInfo.InvariantCulture);

    static void Line(StringBuilder sb, string s) => sb.Append(s).Append('\n');
}
